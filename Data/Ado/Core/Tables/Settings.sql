-------------------------------------------------------------------------------
-- Table for holding key-value pairs.
-------------------------------------------------------------------------------
CREATE TABLE [core].[Settings]
(
    [RowId]        INT IDENTITY (1, 1) NOT NULL,
    [RowVersion]   TIMESTAMP           NOT NULL,
    [IsActive]     BIT                 NOT NULL,
    [Flags]        BIGINT              NOT NULL,
    [DateCreated]  DATETIME            NOT NULL,
    [DateModified] DATETIME            NOT NULL,
    [Name]         NVARCHAR(64)        NOT NULL,
    [Value]        NVARCHAR(1024)          NULL
)
GO

ALTER TABLE [core].[Settings]
    ADD CONSTRAINT [PK_Settings] PRIMARY KEY CLUSTERED ([RowId] ASC) WITH (ALLOW_PAGE_LOCKS = ON, ALLOW_ROW_LOCKS = ON, PAD_INDEX = OFF, IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF);
GO

CREATE UNIQUE NONCLUSTERED INDEX [IX_Settings_Name]
    ON [core].[Settings]([Name] ASC) WITH (ALLOW_PAGE_LOCKS = ON, ALLOW_ROW_LOCKS = ON, PAD_INDEX = OFF, SORT_IN_TEMPDB = OFF, DROP_EXISTING = OFF, IGNORE_DUP_KEY = OFF, STATISTICS_NORECOMPUTE = OFF, ONLINE = OFF, MAXDOP = 0)
    ON [PRIMARY];
GO