namespace Codev.Core.Interface
{
    ///------------------------------------------------------------------------
    /// <summary>
    /// This interface defines the common contract for a table.
    /// </summary>
    ///------------------------------------------------------------------------
    public interface IDatabaseTable
    {
        ///--------------------------------------------------------------------
        /// <summary>
        /// Create a table.
        /// </summary>
        ///--------------------------------------------------------------------
        void CreateTable();

        ///--------------------------------------------------------------------
        /// <summary>
        /// Create the contents of the table (Truncate).
        /// </summary>
        ///--------------------------------------------------------------------
        void ClearTable();

        ///--------------------------------------------------------------------
        /// <summary>
        /// Create keys.
        /// </summary>
        ///--------------------------------------------------------------------
        void CreatePrimaryKey();

        ///--------------------------------------------------------------------
        /// <summary>
        /// Create foreign key references.
        /// </summary>
        ///--------------------------------------------------------------------
        void CreateForeignKeys();

        ///--------------------------------------------------------------------
        /// <summary>
        /// Create indexes.
        /// </summary>
        ///--------------------------------------------------------------------
        void CreateIndexes();
    }
}
